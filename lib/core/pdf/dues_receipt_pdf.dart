import 'dart:typed_data';

import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

/// Receipt PDF for a dues/levy payment — mirrors
/// core/pdf/utility_receipt_pdf.dart's layout and the same "NGN" (not "₦")
/// workaround for the built-in fonts' missing naira glyph.
String _naira(int amount) => 'NGN ${NumberFormat('#,##0').format(amount)}';

pw.Widget _row(String label, String value, {bool bold = false}) => pw.Padding(
  padding: pw.EdgeInsets.symmetric(vertical: 3),
  child: pw.Row(
    crossAxisAlignment: pw.CrossAxisAlignment.start,
    children: [
      pw.SizedBox(
        width: 120,
        child: pw.Text(
          label,
          style: pw.TextStyle(fontSize: 10, color: PdfColors.grey600),
        ),
      ),
      pw.Expanded(
        child: pw.Text(
          value,
          style: pw.TextStyle(
            fontSize: 11,
            font: bold ? pw.Font.timesBold() : null,
          ),
        ),
      ),
    ],
  ),
);

Future<Uint8List> buildDuesReceiptPdf({
  required String reference,
  required String purpose, // 'DUES' | 'LEVY'
  required String method, // 'PAYSTACK' | 'WALLET'
  required int amount,
  required String residentName,
  required String house,
}) {
  final title = purpose == 'LEVY' ? 'Levy Payment Receipt' : 'Dues Payment Receipt';
  final methodLabel = method == 'WALLET' ? 'Wallet' : 'Paystack';
  final dateLabel = DateFormat('d MMM yyyy · HH:mm').format(DateTime.now());

  final doc = pw.Document();
  doc.addPage(
    pw.Page(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.fromLTRB(40, 44, 40, 40),
      build: (context) => pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Container(
            width: double.infinity,
            padding: pw.EdgeInsets.symmetric(vertical: 18, horizontal: 20),
            decoration: const pw.BoxDecoration(color: PdfColor.fromInt(0xFF1B4332)),
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text(
                  'MyCove',
                  style: pw.TextStyle(
                    fontSize: 24,
                    font: pw.Font.timesBold(),
                    color: PdfColors.white,
                  ),
                ),
                pw.SizedBox(height: 2),
                pw.Text(title, style: pw.TextStyle(fontSize: 11, color: PdfColors.white)),
              ],
            ),
          ),
          pw.SizedBox(height: 16),
          _row('Reference', reference),
          _row('Date', dateLabel),
          _row('Method', methodLabel),
          pw.SizedBox(height: 12),
          pw.Text('CUSTOMER', style: pw.TextStyle(fontSize: 9, color: PdfColors.grey600)),
          pw.Divider(),
          _row('Name', residentName),
          if (house.isNotEmpty) _row('House', house),
          pw.SizedBox(height: 12),
          pw.Text('TRANSACTION DETAILS', style: pw.TextStyle(fontSize: 9, color: PdfColors.grey600)),
          pw.Divider(),
          _row('Total paid', _naira(amount), bold: true),
          pw.Spacer(),
          pw.Divider(),
          pw.Text(
            'Generated by MyCove. For help, contact your estate management office.',
            style: pw.TextStyle(fontSize: 8.5, color: PdfColors.grey600),
          ),
        ],
      ),
    ),
  );
  return doc.save();
}

/// Opens the share sheet with the generated PDF — its "Save to Files" action
/// is the download path, while WhatsApp/email cover forwarding.
Future<void> shareDuesReceiptPdf({
  required String reference,
  required String purpose,
  required String method,
  required int amount,
  required String residentName,
  required String house,
}) async {
  final bytes = await buildDuesReceiptPdf(
    reference: reference,
    purpose: purpose,
    method: method,
    amount: amount,
    residentName: residentName,
    house: house,
  );
  await Printing.sharePdf(bytes: bytes, filename: 'mycove-receipt-$reference.pdf');
}
